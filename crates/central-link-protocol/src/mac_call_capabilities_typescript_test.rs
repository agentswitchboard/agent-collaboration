//! Export the capabilities entry without changing the other machine-link shapes.

use super::{HandledMacCalls, MacCallKind, MacCapabilities};
use crate::{DataFrame, FrameDirection, LinkFrame, encode_text};
use std::{fs, path::Path};

// The focused root projects the one tagged entry of DataFrame. Its payload
// comes from the actual codec type, and the encoded frame checks the tag.
#[derive(serde::Serialize, specta::Type)]
#[serde(tag = "kind", rename_all = "camelCase")]
enum MacCapabilitiesFrame {
    MacCapabilities(MacCapabilities),
}

#[test]
fn mac_capabilities_typescript_matches_the_serde_wire() {
    let announcement = MacCapabilities {
        handled_calls: HandledMacCalls::try_from(vec![MacCallKind::ApprovalNotice]).unwrap(),
    };
    let frame = LinkFrame::Data(DataFrame::MacCapabilities(announcement.clone()));
    assert_eq!(
        serde_json::to_string(&MacCapabilitiesFrame::MacCapabilities(announcement)).unwrap(),
        encode_text(&frame, FrameDirection::ToCentral).unwrap(),
    );

    let roots = specta::Types::default().register::<MacCapabilitiesFrame>();
    let exported = specta_typescript::Typescript::default()
        .header("// Generated by central-link-protocol's Mac call capabilities export test.")
        .export(&roots, specta_serde::PhasesFormat)
        .unwrap();
    let generated = exported
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
        + "\n";
    let artifact = Path::new(env!("CARGO_MANIFEST_DIR")).join("contracts/mac-call-capabilities.ts");
    if std::env::var("UPDATE_MAC_CALL_CAPABILITIES_TYPES").as_deref() == Ok("1") {
        fs::write(&artifact, &generated).unwrap();
    }
    assert_eq!(
        fs::read(artifact).unwrap(),
        generated.as_bytes(),
        "regenerate with UPDATE_MAC_CALL_CAPABILITIES_TYPES=1",
    );
}
