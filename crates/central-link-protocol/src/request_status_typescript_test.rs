//! Project the new inconclusive answer through the same Serde wire as the host writer.

use super::RequestStatusAnswer;
use crate::{DataFrame, FrameDirection, LinkFrame, encode_text};
use std::{fs, path::Path};

#[derive(serde::Serialize, specta::Type)]
#[serde(
    tag = "kind",
    content = "value",
    rename_all = "camelCase",
    deny_unknown_fields
)]
enum UnavailableStatusAnswer {
    CentralUnavailable {},
}

#[derive(serde::Serialize, specta::Type)]
#[serde(
    tag = "kind",
    rename_all = "camelCase",
    rename_all_fields = "camelCase",
    deny_unknown_fields
)]
enum UnavailableStatusFrame {
    RequestStatusReply {
        correlation_id: String,
        result: UnavailableStatusAnswer,
    },
}

#[test]
fn unavailable_status_typescript_matches_the_serde_wire() {
    let correlation = "019f0000-0000-7000-8000-000000000001";
    let actual = LinkFrame::Data(DataFrame::RequestStatusReply {
        correlation_id: correlation.parse().unwrap(),
        result: Box::new(RequestStatusAnswer::CentralUnavailable {}),
    });
    let projection = UnavailableStatusFrame::RequestStatusReply {
        correlation_id: correlation.into(),
        result: UnavailableStatusAnswer::CentralUnavailable {},
    };
    assert_eq!(
        serde_json::to_value(projection).unwrap(),
        serde_json::from_str::<serde_json::Value>(
            &encode_text(&actual, FrameDirection::ToRouter).unwrap(),
        )
        .unwrap(),
    );

    let generated = specta_typescript::Typescript::default()
        .header("// Generated by central-link-protocol's inconclusive status export test.")
        .export(
            &specta::Types::default().register::<UnavailableStatusFrame>(),
            specta_serde::PhasesFormat,
        )
        .unwrap();
    let generated = generated
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
        + "\n";
    let artifact =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("contracts/request-status-unavailable.ts");
    if std::env::var("UPDATE_REQUEST_STATUS_TYPES").as_deref() == Ok("1") {
        fs::write(&artifact, &generated).unwrap();
    }
    assert_eq!(fs::read(artifact).unwrap(), generated.as_bytes());
}
