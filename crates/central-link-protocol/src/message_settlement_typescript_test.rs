//! Keep the message settlement wire roots and their generated TypeScript in sync.
use std::{fs, path::Path};

use specta::Types;
use workspace_model::central_mail::{MessageOutcome, MessageRefusal, MessageStatus};

use super::{Receipt, ReceiptBatch, ReceiptKind, ReceiptResult};

#[test]
fn message_settlement_typescript_matches_the_serde_wire() {
    let roots = Types::default()
        .register::<Receipt>()
        .register::<ReceiptBatch>()
        .register::<ReceiptKind>()
        .register::<ReceiptResult>()
        .register::<MessageRefusal>()
        .register::<MessageOutcome>()
        .register::<MessageStatus>();
    let exported = specta_typescript::Typescript::default()
        .header("// Generated by central-link-protocol's message settlement export test.")
        .export(&roots, specta_serde::PhasesFormat)
        .expect("export the message settlement wire types");
    let generated = exported
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
        + "\n";
    for root_name in [
        "Receipt",
        "ReceiptBatch",
        "ReceiptKind",
        "ReceiptResult",
        "MessageRefusal",
        "MessageOutcome",
        "MessageStatus",
    ] {
        assert!(
            generated.contains(&format!("export type {root_name} ")),
            "missing message settlement wire root {root_name}"
        );
    }
    for removed in ["notSeen", "sessionClosed", "WaitingReason", "waiting:"] {
        assert!(!generated.contains(removed), "removed wire field {removed}");
    }

    let artifact = Path::new(env!("CARGO_MANIFEST_DIR")).join("contracts/message-settlement.ts");
    if std::env::var("UPDATE_MESSAGE_SETTLEMENT_TYPES").as_deref() == Ok("1") {
        fs::write(&artifact, &generated).expect("write message settlement types");
    }
    assert_eq!(
        fs::read(artifact).expect("read message settlement types"),
        generated.as_bytes(),
        "regenerate with UPDATE_MESSAGE_SETTLEMENT_TYPES=1"
    );
}
