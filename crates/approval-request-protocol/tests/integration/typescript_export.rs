use std::path::Path;

use specta::Types;
use specta_typescript::Typescript;

use crate::wire_roots::check_expected_typescript_roots;

fn generate_approval_typescript() -> String {
    let types = Types::default()
        .register::<approval_request_protocol::Raise>()
        .register::<approval_request_protocol::RaiseReply>()
        .register::<approval_request_protocol::RegisterRunRequest>()
        .register::<approval_request_protocol::RegisterRunReply>()
        .register::<approval_request_protocol::StopRequest>()
        .register::<approval_request_protocol::StopReply>()
        .register::<approval_request_protocol::OfferEnding>()
        .register::<approval_request_protocol::ReportDeliveryRequest>()
        .register::<approval_request_protocol::ReportDeliveryReply>()
        .register::<approval_request_protocol::ListPersonRequests>()
        .register::<approval_request_protocol::ListPersonRequestsReply>()
        .register::<approval_request_protocol::ReadPersonRequest>()
        .register::<approval_request_protocol::ReadPersonRequestReply>()
        .register::<approval_request_protocol::DecidePersonRequest>()
        .register::<approval_request_protocol::DecidePersonReply>()
        .register::<approval_request_protocol::ListSessionRequests>()
        .register::<approval_request_protocol::ListSessionRequestsReply>()
        .register::<approval_request_protocol::ReadSessionRequest>()
        .register::<approval_request_protocol::ReadSessionRequestReply>()
        .register::<approval_request_protocol::DecideSessionRequest>()
        .register::<approval_request_protocol::DecideSessionReply>()
        .register::<approval_request_protocol::PassOnRequest>()
        .register::<approval_request_protocol::PassOnReply>()
        .register::<approval_request_protocol::WaitingListAtRequest>()
        .register::<approval_request_protocol::WaitingListAtReply>()
        .register::<approval_request_protocol::RequestState>();
    let generated = Typescript::default()
        .header("// Generated by approval-request-protocol's TypeScript export test.")
        .export(&types, specta_serde::PhasesFormat)
        .expect("generate approval request TypeScript from the Serde wire types");
    let without_trailing_whitespace = generated
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    format!("{}\n", without_trailing_whitespace.trim_end())
}

#[test]
fn approval_typescript_contains_expected_roots_and_matches_generation() {
    let destination = Path::new(env!("CARGO_MANIFEST_DIR")).join("contracts/approval-requests.ts");
    let generated = generate_approval_typescript();
    check_expected_typescript_roots(&generated);
    if std::env::var_os("UPDATE_APPROVAL_TYPES").is_some_and(|update| update == "1") {
        std::fs::write(&destination, &generated).expect("write generated approval contracts");
    }
    let committed = std::fs::read_to_string(&destination).unwrap_or_else(|error| {
        panic!(
            "read {}: {error}; generate with UPDATE_APPROVAL_TYPES=1",
            destination.display()
        )
    });
    check_expected_typescript_roots(&committed);
    assert_eq!(
        generated.as_bytes(),
        committed.as_bytes(),
        "approval wire drift; regenerate with UPDATE_APPROVAL_TYPES=1"
    );
}
